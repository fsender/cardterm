// 布局契约（用户规格）：
//   - 候选框：双列 × 5 行（左 1~5 / 右 6~9 + 状态行），每行 15px（文本 8×14，
//     上方留 1px），内容 75px + 上下边框各 2px = 固定总高 79px；
//   - 宽度动态：每列宽 = 该列当前页最宽条目（格），条目截断 16 格
//     （序号+句点+7 汉字）；W = 24 + 8*(L+R)（左右圆角区各 8px，中间空格 8px）；
//   - 圆角：外框 r10（外 r + 内 r-1 + 内 r-2 三笔，无空洞），选项高亮块在
//     间隙侧伸 4px 凸条（4×13 居中 / Tab 4×14）雕 2×2 出双圆角/单圆角；
//   - 颜色：toast/全屏横幅同款配置项 —— 底=black(bright0)、边框/Tab=blue(bright4)、
//     白=white(bright7)；选中=白底黑字，Tab=蓝底黑字，未选中=黑底白字；
//     编辑行=regular7 前景、透明背景（不受终端程序控制）；
//   - 定位：框跟光标（上半屏框在下方 / 下半屏在上方；53×17 中央行在下方、
//     中央列在光标右边），左半屏左缘对齐光标、右半屏右缘对齐，越界贴屏边。
